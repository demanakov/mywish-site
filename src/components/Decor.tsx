/**
 * Декоративный слой страницы — Figma 914:193, первые семь детей фрейма.
 *
 * В макете это подложки, которые лежат под всем контентом и свободно
 * пересекают границы секций (975:2274 идёт с 4679 до 8039), поэтому они
 * вынесены в отдельный слой, а не в секции.
 *
 * Слоя два:
 *   • сплошные подложки — в макете шире кадра (от −143 до 1746), то есть
 *     задуманы «на вылет». Тянутся на всю ширину окна, иначе на широком
 *     мониторе виден шов там, где заканчивается сцена 1440;
 *   • водяные знаки — привязаны к конкретным местам сетки, поэтому остаются
 *     на координатах сцены. Их прозрачность 4–8 % задана здесь: PNG-экспорт
 *     Figma запекает розовый фон, но при таких значениях результат совпадает
 *     с макетом, потому что фон под ними тот же самый.
 *
 * Координаты — от начала сцены (макет y − 956), порядок — как в макете.
 */

/** Сплошные подложки: растут вместе с окном, по вертикали — как в макете. */
type Band = {
  file: string;
  node: string;
  y: number;
  h: number;
  /** Ширина подложки в макете. */
  w: number;
  /** Смещение центра подложки относительно центра кадра 1440. */
  dx: number;
};

/**
 * Во сколько раз подложка шире окна. Держим ту же долю, что в макете, —
 * иначе на широком мониторе у фигуры видны загнутые вниз края, которых в
 * макете за кадром. Нижняя граница — чтобы смещённая вбок подложка всё
 * равно докрывала противоположный край.
 */
const widthRatio = (b: Band) =>
  Math.max(b.w / 1440, 1 / (1 - (2 * Math.abs(b.dx)) / b.w));

