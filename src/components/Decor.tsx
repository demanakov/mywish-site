/**
 * Тёмные участки фона — для перекраски плавающей шапки.
 *
 * Логотип у нас одноцветный (#0E1736 сплошной заливкой), и на синей подложке
 * он пропадает. Шапка это отслеживает и переключается в светлую схему, но
 * узнать цвет фона в браузере нечем: тёмное здесь — содержимое картинок, а не
 * background элементов. Поэтому тёмные зоны описаны явно.
 *
 * Границы не взяты из макета, а измерены по отрендеренной странице:
 * `node scripts/backdrop.mjs` печатает диапазоны, где яркость под шапкой ниже
 * порога. Совпадения с координатами подложек ждать не надо: у полосы 988:30
 * верхний край скруглён, а снизу её перекрывает светлая packages-band, так что
 * тёмной она выглядит не на всю свою высоту (3147…3911), а только 3172…3852.
 * Взят диапазон из колонки логотипа (x 131…302) — по нему и идёт переключение.
 *
 * Прямоугольники описывают именно видимую тёмную часть. Если добавится новая
 * тёмная секция — прогнать скрипт и дописать сюда строку.
 *
 * Тёмного на странице два места, но здесь только одно: CTA-баннер 914:2083
 * (тоже navy) до полосы шапки не доезжает. Страница кончается раньше, чем он
 * успевает подняться наверх, — самая нижняя достижимая точка сцены 8845, а
 * баннер начинается на 9057. Проверено на окнах 700, 900 и 1200: отношение
 * держится, потому что hero равен высоте окна и масштаб ведёт та же высота.
 */
const DARK_BACKDROPS: { name: string; y: number; h: number }[] = [
  /* Полоса под «REELS» и «один человек на весь праздник» (988:30). */
  { name: "reels-manager", y: 3172, h: 680 },
];

export default function Decor() {
  return (
    <div aria-hidden className="decor-layer pointer-events-none absolute inset-0">
      {DARK_BACKDROPS.map((zone) => (
        <div
          key={zone.name}
          data-header-backdrop="dark"
          data-zone={zone.name}
          style={box(0, zone.y, 1440, zone.h)}
        />
      ))}

      <div className="decor-bleed">
        {BANDS.map((b) => (
          // eslint-disable-next-line @next/next/no-img-element
          <img
            key={b.file}
            src={`/figma/decor/${b.file}`}
            alt=""
            data-node-id={b.node}
            loading="lazy"
            decoding="async"
            style={
              {
                top: px(b.y),
                height: px(b.h),
                "--w": px(b.w),
                "--k": widthRatio(b).toFixed(5),
                "--dxp": `${((b.dx / b.w) * 100).toFixed(4)}%`,
              } as React.CSSProperties
            }
          />
        ))}
      </div>

      <div className="absolute inset-0 overflow-hidden">
        {MARKS.map((m) => (
          // eslint-disable-next-line @next/next/no-img-element
          <img
            key={m.file}
            src={`/figma/decor/${m.file}`}
            alt=""
            data-node-id={m.node}
            loading="lazy"
            decoding="async"
            className="max-w-none"
            style={{ ...box(m.x, m.y, m.w, m.h), opacity: m.opacity }}
          />
        ))}
      </div>
    </div>
  );
}
